// Minimal shape needed to synthesize a brief — matches the relevant fields of
// ClientBrief without importing it here (avoids a cross-module dependency).
export type BriefSourceClient = {
  name?: string;
  niche?: string;
  task?: string;
  redFlags?: string[];
  greyFlags?: string[];
};

// Every client (119 of them) needs a brief the moment "Провести міт та
// зібрати бриф" is clicked — including scam/red-flag ones — so the marketer
// always has something concrete to evaluate, never a "not prepared" dead
// end. Hand-curated CLIENT_BRIEFS covers the original ~18 flagship clients;
// everyone else gets one synthesized here from their niche, task text, and
// red/grey flags. Synthesized briefs aim for ~85% fill — most fields pull
// real signal out of the task text (budget, check size, lead/sale targets,
// handles, existing-ads mentions) or a niche-aware generic answer; only the
// handful of fields a client genuinely wouldn't volunteer unprompted
// (competitors, exact repeat-purchase rate, margin %, GTM/telephony/brand
// book specifics) are left as "не вказано" for the marketer to dig up live.
const extractHandle = (text: string): string | null => {
  const m = text.match(/@[a-zA-Z0-9_.]{3,}/);
  return m ? m[0] : null;
};

const extractUrl = (text: string): string | null => {
  const m = text.match(/\b([a-zA-Z0-9-]+\.(com|ua|com\.ua|io|net|org)(\/[^\s,)]*)?)/i);
  return m ? m[0] : null;
};

const extractBudget = (text: string): string | null => {
  const m = text.match(/бюджет[^.]{0,30}?(\d[\d\s]{0,7})\s*(грн\/міс|грн|\$\/міс|\$|USD|usdt|к\/міс|к\b)/i);
  if (m) return `${m[1].trim()} ${m[2]}`.replace(/\s+/g, ' ');
  const fallback = text.match(/(\d[\d\s]{0,7})\s*(грн\/міс|\$\/міс|к\/міс)/i);
  return fallback ? fallback[0].trim().replace(/\s+/g, ' ') : null;
};

const extractAvgCheck = (text: string): string | null => {
  const patterns = [
    /середній чек[^.]{0,40}?(\d[\d\s]{1,6})\s*(грн|\$|USD|к\b)/i,
    /чек\s*(?:від|—|-)?\s*(\d[\d\s]{1,6})\s*(грн|\$|USD|к\b)/i,
    /по\s*(\d[\d\s]{1,6})\s*грн/i,
  ];
  for (const re of patterns) {
    const m = text.match(re);
    if (m) return m[0].trim().replace(/\s+/g, ' ');
  }
  return null;
};

const extractLeadGoal = (text: string): string | null => {
  const m = text.match(/(\d[\d\s-]{1,8})\s*(клієнт(?:ів|и)?|заяв(?:ок|ки)|лід(?:ів|и)?|продаж(?:ів|і)?|штук|замовлень)\s*(?:\/|за |на )?\s*(день|тиждень|міс(?:яць)?)?/i);
  return m ? m[0].trim().replace(/\s+/g, ' ') : null;
};

const extractCPL = (text: string): string | null => {
  const patterns = [
    /(\d[\d\s]{1,6})\s*грн\s*за\s*(клієнта|ліда|заявку|продажу|продаж)/i,
    /(\d[\d\s]{1,6})\s*(грн|\$)\s*(?:\/|за )\s*(клік|ліда|лід)/i,
  ];
  for (const re of patterns) {
    const m = text.match(re);
    if (m) return m[0].trim().replace(/\s+/g, ' ');
  }
  return null;
};

const extractRomi = (text: string): string | null => {
  const m = text.match(/ROMI[^.]{0,20}?(\d{2,4})\s*%|ROAS[^.]{0,20}?(\d[\d.]{0,4})/i);
  return m ? m[0].trim() : null;
};

const hasExistingAdsMention = (text: string): string | null => {
  if (/самі (крутим|пробували|запускали|давали)|запускали.{0,15}(таргет|рекламу)|пробували.{0,15}(таргет|рекламу|фейсбук|мета)/i.test(text)) {
    return 'Так, пробували самостійно — результат клієнта не влаштував';
  }
  if (/ніколи.{0,10}(не давав|не робив|не пускав).{0,15}(реклам|таргет)/i.test(text)) {
    return 'Ніколи не запускали платну рекламу';
  }
  return null;
};

// Every field below reflects that the meeting/call has ALREADY happened —
// "Провести міт та зібрати бриф" means the marketer just finished talking
// to the client, so nothing here should defer to "уточнити на дзвінку".
// Where the client genuinely wouldn't have a precise number (margin,
// repeat-purchase rate, exact conversion), the field states that plainly
// ("клієнт не рахує/не назвав") instead of pointing at a future call.
export const synthesizeBrief = (client: BriefSourceClient): BriefField[] => {
  const task = client.task || '';
  const niche = client.niche || 'не вказана ніша';
  const reds = new Set(client.redFlags || []);
  const greys = new Set(client.greyFlags || []);
  const handle = extractHandle(task);
  const url = extractUrl(task);
  const budget = extractBudget(task);
  const avgCheck = extractAvgCheck(task);
  const leadGoal = extractLeadGoal(task);
  const cpl = extractCPL(task);
  const romi = extractRomi(task);
  const existingAds = hasExistingAdsMention(task);

  const noCrm = reds.has('no_crm');
  const noSales = reds.has('no_sales_team');
  const soloOwner = reds.has('solo_owner');
  const isScam = reds.has('scam');
  const isTelegram = greys.has('telegram_ads');
  const isCounterfeit = greys.has('counterfeit');
  const isCrypto = greys.has('crypto');
  const isInfobiz = greys.has('questionable_infobiz');
  const noWebsite = noCrm || soloOwner || isTelegram || isCounterfeit;

  return fill([
    url || (noWebsite ? 'Немає сайту, продажі через соцмережі/директ' : 'Сайту немає, працює тільки через соцмережі'), // сайт
    handle || (isTelegram ? 'Тільки Telegram-канал, без інших соцмереж' : 'Instagram, посилання скинув клієнт'), // соцмережі
    'Клієнт не орієнтується у конкурентах, назвав нішу загалом без конкретних імен', // конкуренти
    'Україна, здебільшого великі та середні міста', // географія
    `ЦА за нішею "${niche}": дорослі платоспроможні клієнти, точний портрет клієнт описав лише загально`, // опис клієнта
    `За нішею "${niche}" — базові позиції клієнт назвав орієнтовно, без детальної розбивки попиту`, // послуги з найб. попитом
    'Чіткого пріоритету не розставляв — назвав усі напрямки однаково важливими', // порядок пріоритету
    leadGoal || '20-30 заявок на місяць — орієнтовно, точної цифри не називав', // скільки лідів хочете
    isScam || soloOwner ? 'Нестабільно/хаотично, точних цифр не веде' : 'Заявки йдуть нерегулярно, точну кількість клієнт не рахує', // скільки лідів зараз
    cpl || 'Чіткої суми не називав — орієнтується на здоровий глузд відповідно до чека', // прийнятна вартість ліда
    'Конверсію в продаж не рахує — немає системи обліку', // конверсія в продаж
    avgCheck || 'Точну суму не озвучив, лише приблизний діапазон', // середній чек
    'Статистики повторних покупок не веде', // повторні покупки
    'Клієнт не готовий озвучувати маржинальність', // маржинальність
    isScam ? 'Клієнт згадує "вигідні умови", потребує перевірки на реалістичність' : 'Періодично робить знижки, чіткого графіка акцій немає', // акції
    isScam ? 'Клієнт сам вважає свою пропозицію унікальною — потребує перевірки на реалістичність' : `Чіткого УТП не сформулював, позиціонує себе як якісний варіант у ніші "${niche}"`, // УТП
    isScam || soloOwner ? 'Тільки телефонні фото/скріни, професійного контенту немає' : 'Є кілька телефонних фото, професійного контенту небагато', // готові фото
    budget || romi || 'Точну суму не називав, готовий стартувати з невеликого бюджету', // бюджет
    existingAds || 'Раніше рекламу не запускав', // чи працює реклама зараз
    'Не встановлено', // GTM/GA
    'Немає окремої телефонії, приймає дзвінки на особистий номер', // телефонія
    noCrm ? 'Немає CRM-системи' : 'CRM не використовує, веде облік вручну', // CRM
    noSales ? 'Немає, власник сам обробляє заявки' : (soloOwner ? 'Власник працює сам, найманих немає' : 'Продажами займається сам власник'), // менеджер з продажу
    (isCounterfeit || isCrypto || isInfobiz) ? 'Немає — потребує окремого обговорення через специфіку ніші' : 'Брендбуку немає, є тільки логотип і назва', // брендбук
  ]);
};

